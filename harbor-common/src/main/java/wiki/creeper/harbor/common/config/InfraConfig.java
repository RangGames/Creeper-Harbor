package wiki.creeper.harbor.common.config;

import java.nio.file.Path;
import java.time.DateTimeException;
import java.time.DayOfWeek;
import java.time.LocalDate;
import java.time.LocalTime;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Pattern;
import org.jspecify.annotations.Nullable;
import wiki.creeper.harbor.common.db.DatabaseConfig;
import wiki.creeper.harbor.common.model.SeasonId;
import wiki.creeper.harbor.common.pack.ZipConformance;
import wiki.creeper.harbor.common.redis.RedisConfig;
import wiki.creeper.harbor.common.session.SessionLocks;
import wiki.creeper.harbor.common.time.HarborTime;
import wiki.creeper.harbor.common.util.Result;
import wiki.creeper.harbor.common.util.ValidationErrors;
import wiki.creeper.harbor.common.yaml.YamlNode;

/**
 * Infrastructure config (harbor-infra.yml). Holds only per-server values (server ID, DB/Redis
 * addresses). Game numbers live in the content's balance.yml.
 *
 * @param serverId server ID (session locks, message sender). Must match the server name registered
 *     in the proxy.
 * @param dev dev mode: warnings on detected main-thread I/O, etc.
 * @param contentDir content folder (null means plugins/Harbor/content)
 * @param lobbyServer lobby server name to send players to on resource pack refusal or session wait
 * @param packBuild whether this server builds the resource pack from the asset folder and uploads
 *     it to the CDN (null means no build, proposed)
 */
public record InfraConfig(
        String serverId,
        ServerRole role,
        boolean dev,
        DatabaseConfig database,
        RedisConfig redis,
        SeasonId season,
        LocalDate seasonStart,
        ZoneId zone,
        LocalTime dailyReset,
        DayOfWeek weeklyReset,
        @Nullable Path contentDir,
        String lobbyServer,
        List<ResourcePack> resourcePacks,
        @Nullable PackBuild packBuild) {

    /** Required resource pack sent on join. sha1 is 40 hex digits. */
    public record ResourcePack(String id, String url, String sha1) {}

    /**
     * Automatic resource pack build and upload (harbor-infra.yml pack:).
     *
     * @param source asset folder (null means plugins/Harbor/pack)
     * @param cdnUrl CDN address (e.g. https://cdn.creeper.wiki)
     * @param apiKey CDN API key (never logged)
     * @param namespace CDN namespace (lowercase letters, digits, -)
     * @param version CDN version slot (e.g. 1.0). The URL changes with the content hash, so it can
     *     stay the same when the pack changes
     * @param format pack format to use when there is no pack.mcmeta (e.g. 97.1)
     * @param fileName name of the uploaded file (with extension)
     * @param merge other resource packs to merge in (folder or zip, path relative to the server
     *     folder, earlier wins. Packs in plugins/Harbor/pack-merge/ are appended automatically,
     *     proposed)
     * @param autoMerge also merge packs generated by installed plugins (ModelEngine, BetterModel,
     *     ...; see PluginPacks), after merge (proposed)
     * @param watch rebuild automatically when the asset folder or a merged pack changes, e.g. after
     *     a ModelEngine reload (proposed)
     * @param optimize lossless PackSquash-style optimizations: JSON minify, PNG recompression,
     *     storing already-compressed files (proposed)
     * @param keep file extensions (without dot) to put in the pack although Minecraft does not read
     *     them (by default only pack file types go in; README.md, .bbmodel… are left out)
     * @param zip zip conformance level (pedantic standard zip, balanced shared duplicate data,
     *     disregard extraction protection; PackSquash names, proposed)
     */
    public record PackBuild(
            @Nullable Path source,
            String cdnUrl,
            String apiKey,
            String namespace,
            String version,
            String format,
            String description,
            String fileName,
            List<Path> merge,
            boolean autoMerge,
            boolean watch,
            boolean optimize,
            List<String> keep,
            ZipConformance zip) {

        public PackBuild {
            merge = List.copyOf(merge);
            keep = List.copyOf(keep);
        }

        @Override
        public String toString() {
            return "PackBuild[cdn="
                    + cdnUrl
                    + ", namespace="
                    + namespace
                    + ", version="
                    + version
                    + "]";
        }
    }

    private static final Pattern SHA1 = Pattern.compile("[0-9a-f]{40}");

    public HarborTime time() {
        return new HarborTime(java.time.Clock.system(zone), dailyReset, weeklyReset, seasonStart);
    }

    public static Result<InfraConfig, ValidationErrors> load(Path file) {
        ValidationErrors errors = new ValidationErrors();
        Optional<YamlNode> root = YamlNode.read(file, file.getFileName().toString(), errors);
        if (root.isEmpty()) {
            return Result.err(errors);
        }
        InfraConfig config = parse(root.get());
        return errors.isEmpty() ? Result.ok(config) : Result.err(errors);
    }

    static InfraConfig parse(YamlNode root) {
        root.allowOnly(
                Set.of(
                        "server",
                        "dev",
                        "database",
                        "redis",
                        "season",
                        "time",
                        "content_dir",
                        "lobby_server",
                        "resource_packs",
                        "pack"));

        YamlNode server = root.require("server").orElse(root);
        String serverId = server.string("id");
        try {
            if (!serverId.isEmpty()) {
                SessionLocks.requireServerId(serverId);
            }
        } catch (IllegalArgumentException e) {
            server.error(String.valueOf(e.getMessage()));
        }
        ServerRole role = server.enumValue("role", ServerRole.class).orElse(ServerRole.MAIN);

        YamlNode db = root.require("database").orElse(root);
        DatabaseConfig database =
                new DatabaseConfig(
                        db.string("host", "localhost"),
                        db.integer("port", 3306, 1, 65535),
                        db.string("name", "harbor"),
                        db.string("user"),
                        db.string("password", ""),
                        db.integer("pool_size", role.defaultPoolSize(), 1, 200),
                        "harbor-" + (serverId.isEmpty() ? "unknown" : serverId));

        RedisConfig redis = new RedisConfig(root.require("redis").orElse(root).string("uri"));

        YamlNode seasonNode = root.require("season").orElse(root);
        int seasonNumber = seasonNode.integer("id", 1, 1, 1000);
        LocalDate seasonStart = LocalDate.now(HarborTime.DEFAULT_ZONE);
        Optional<YamlNode> start = seasonNode.require("start");
        if (start.isPresent()) {
            try {
                seasonStart = LocalDate.parse(start.get().asString());
            } catch (DateTimeException e) {
                start.get().error("날짜는 2027-09-01 형식이어야 합니다");
            }
        }

        ZoneId zone = HarborTime.DEFAULT_ZONE;
        LocalTime dailyReset = LocalTime.of(6, 0);
        DayOfWeek weeklyReset = DayOfWeek.MONDAY;
        Optional<YamlNode> time = root.get("time");
        if (time.isPresent()) {
            YamlNode t = time.get();
            try {
                zone = ZoneId.of(t.string("zone", HarborTime.DEFAULT_ZONE.getId()));
                dailyReset = LocalTime.parse(t.string("daily_reset", "06:00"));
                weeklyReset =
                        DayOfWeek.valueOf(
                                t.string("weekly_reset", "MONDAY").toUpperCase(Locale.ROOT));
            } catch (DateTimeException | IllegalArgumentException e) {
                t.error(
                        "time 설정이 틀렸습니다 (zone: Asia/Seoul, daily_reset: \"06:00\", weekly_reset: MONDAY): "
                                + e.getMessage());
            }
        }

        List<ResourcePack> packs = new ArrayList<>();
        for (YamlNode pack : root.list("resource_packs")) {
            String sha1 = pack.string("sha1").toLowerCase(Locale.ROOT);
            if (!SHA1.matcher(sha1).matches()) {
                pack.error("sha1은 40자리 16진수여야 합니다");
            }
            packs.add(new ResourcePack(pack.string("id"), pack.string("url"), sha1));
        }

        PackBuild packBuild = null;
        Optional<YamlNode> packNode = root.get("pack");
        if (packNode.isPresent() && packNode.get().bool("build", false)) {
            YamlNode p = packNode.get();
            YamlNode cdn = p.require("cdn").orElse(p);
            String namespace = cdn.string("namespace", "creeper-harbor");
            if (!namespace.matches("[a-z][a-z0-9-]*")) {
                cdn.error("namespace는 소문자로 시작하고 소문자·숫자·-만 쓴다: " + namespace);
            }
            String version = cdn.string("version", "1.0");
            if (!version.matches("[0-9]+\\.[0-9]+(\\.[0-9]+)?")) {
                cdn.error("version은 1.0 같은 형식이어야 합니다: " + version);
            }
            String apiKey = cdn.string("api_key");
            String format = p.string("format", "97.1");
            if (!format.matches("[0-9]+(\\.[0-9]+)?")) {
                p.error("format은 97.1 같은 형식이어야 합니다: " + format);
            }
            String zipRaw = p.string("zip", "pedantic");
            Optional<ZipConformance> zipParsed = ZipConformance.parse(zipRaw);
            if (zipParsed.isEmpty()) {
                p.error("zip은 pedantic · balanced · disregard 중 하나입니다: " + zipRaw);
            }
            ZipConformance zipLevel = zipParsed.orElse(ZipConformance.PEDANTIC);
            packBuild =
                    new PackBuild(
                            p.optString("source").map(Path::of).orElse(null),
                            cdn.string("url", "https://cdn.creeper.wiki"),
                            apiKey,
                            namespace,
                            version,
                            format,
                            p.string("description", "크리퍼 항구"),
                            p.string("file_name", "Creeper-Harbor-RP.zip"),
                            p.strings("merge").stream().map(Path::of).toList(),
                            p.bool("auto_merge", true),
                            p.bool("watch", true),
                            p.bool("optimize", true),
                            p.strings("keep").stream()
                                    .map(e -> e.replaceFirst("^\\.", "").toLowerCase(Locale.ROOT))
                                    .toList(),
                            zipLevel);
        }

        return new InfraConfig(
                serverId,
                role,
                root.bool("dev", false),
                database,
                redis,
                new SeasonId(Math.max(1, seasonNumber)),
                seasonStart,
                zone,
                dailyReset,
                weeklyReset,
                root.optString("content_dir").map(Path::of).orElse(null),
                root.string("lobby_server", "lobby"),
                List.copyOf(packs),
                packBuild);
    }
}
